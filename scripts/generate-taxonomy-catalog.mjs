import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, "../../SUPPLY_CHAIN_VARIABLE_TAXONOMY.md");
const outputPath = resolve(here, "../app/taxonomy-catalog.generated.ts");
const source = await readFile(sourcePath, "utf8");

const boundaries = {
  L0: ["## 2. Level 0:", "## 3. Level 1:"],
  L1: ["## 3. Level 1:", "## 4. Level 2:"],
  L2: ["## 4. Level 2:", "## 5. Hierarchy validation"],
};

const parseRows = (level) => {
  const [startMarker, endMarker] = boundaries[level];
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start + startMarker.length);
  if (start < 0 || end < 0) throw new Error(`Could not locate ${level} catalogue boundaries.`);
  return source.slice(start, end).split(/\r?\n/)
    .filter((line) => line.startsWith(`| ${level}-`))
    .map((line) => {
      const cells = line.split("|").slice(1, -1).map((cell) => cell.trim());
      if (cells.length !== 6 && cells.length !== 7) throw new Error(`Unexpected ${level} row: ${line}`);
      if (level === "L0") {
        const [id, domain, name, meaning, examples, relationships] = cells;
        return { id, level, domain, name, meaning, examples, relationships };
      }
      const [id, domain, name, meaning, components, examples, relationships] = cells;
      return { id, level, domain, name, meaning, components, examples, relationships };
    });
};

const catalog = [...parseRows("L0"), ...parseRows("L1"), ...parseRows("L2")];
const counts = Object.fromEntries(["L0", "L1", "L2"].map((level) => [level, catalog.filter((item) => item.level === level).length]));
if (counts.L0 !== 481 || counts.L1 !== 60 || counts.L2 !== 35) {
  throw new Error(`Unexpected taxonomy counts: ${JSON.stringify(counts)}`);
}
if (new Set(catalog.map((item) => item.id)).size !== catalog.length) throw new Error("Taxonomy IDs must be unique.");

const output = `// Generated by scripts/generate-taxonomy-catalog.mjs from SUPPLY_CHAIN_VARIABLE_TAXONOMY.md.\n` +
`export type TaxonomyLevel = "L0" | "L1" | "L2";\n` +
`export type TaxonomyEntry = { id: string; level: TaxonomyLevel; domain: string; name: string; meaning: string; components?: string; examples: string; relationships: string };\n` +
`export const taxonomyCounts = ${JSON.stringify(counts)} as const;\n` +
`export const taxonomyCatalog: readonly TaxonomyEntry[] = ${JSON.stringify(catalog, null, 2)};\n`;

await writeFile(outputPath, output, "utf8");
console.log(`Generated ${catalog.length} taxonomy entries (${counts.L0} L0, ${counts.L1} L1, ${counts.L2} L2).`);
